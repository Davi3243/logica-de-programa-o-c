#include <stdio.h>
int main (void){

int idade = 32;  
 // declaração de uma variável inteira chamada idade e atribuição do valor 32.
printf("sua idade é: %d\n", idade); 
 // exibe o valor da variável idade na tela, usando o especificador de formato %d


float altura = 1.85f; 
 // declaração de uma variável float chamada altura e atribuição do valor 1.85.
printf("sua altura é: %.2f\n", altura); 
 // exibe o valor da variável altura na tela, usando o especificador de formato %.2f


char inicial = 'T'; 
 // declaração de uma variável char chamada inicial e atribuição do valor 'T'.
printf("sua inicial é: %c\n", inicial); 
 // exibe o valor da variável inicial na tela, usando o especificador de formato %c


return 0;
}

 
